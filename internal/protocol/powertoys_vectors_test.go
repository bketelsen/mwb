func TestPowerToysStreamVectors(t *testing.T) {
	plaintext := decodePowerToysHex(t, powerToysPlaintextHex)
	salt := decodePowerToysHex(t, powerToysSaltHex)
	iv := decodePowerToysHex(t, powerToysIVHex)
	for _, tc := range []struct {
		scheme Scheme
		wire   string
		offset int
	}{
		{SchemeLegacy, powerToysLegacyWireHex, 0},
		{SchemeHeader50k, powerToysHeader50kWireHex, HeaderSize},
		{SchemeHeader100k, powerToysHeader100kWireHex, HeaderSize},
	} {
		t.Run(tc.scheme.String(), func(t *testing.T) {
			wire := decodePowerToysHex(t, tc.wire)
			scheme, key, detectedIV, offset, err := DetectScheme(wire[:ProbeSize], powerToysSecurityKey, powerToysMagic)
			if err != nil {
				t.Fatalf("DetectScheme: %v", err)
			}
			if scheme != tc.scheme || offset != tc.offset {
				t.Fatalf("detected scheme/offset = %v/%d, want %v/%d", scheme, offset, tc.scheme, tc.offset)
			}
			if len(wire)-offset != len(plaintext) {
				t.Fatalf("ciphertext length = %d, want %d", len(wire)-offset, len(plaintext))
			}
			dec, err := NewDecryptReader(bytes.NewReader(wire[offset:]), key, detectedIV)
			if err != nil {
				t.Fatal(err)
			}
			got := make([]byte, len(plaintext))
			if _, err := io.ReadFull(dec, got); err != nil {
				t.Fatalf("decrypt .NET wire: %v", err)
			}
			if !bytes.Equal(got, plaintext) {
				t.Errorf("plaintext = %x, want %x", got, plaintext)
			}

			var encrypted bytes.Buffer
			encryptionKey, encryptionIV := DeriveKey(powerToysSecurityKey), FixedIV()
			if tc.scheme.HasHeader() {
				encrypted.Write(salt)
				encrypted.Write(iv)
				encryptionKey = DeriveSchemeKey(powerToysSecurityKey, salt, tc.scheme)
				encryptionIV = iv
			}
			enc, err := NewEncryptWriter(&encrypted, encryptionKey, encryptionIV)
			if err != nil {
				t.Fatal(err)
			}
			if n, err := enc.Write(plaintext); err != nil || n != len(plaintext) {
				t.Fatalf("encrypt: wrote %d bytes, error %v", n, err)
			}
			if !bytes.Equal(encrypted.Bytes(), wire) {
				t.Errorf("wire = %x, want .NET wire %x", encrypted.Bytes(), wire)
			}
		})
	}
}

func TestSchemeHeadersAreRandom(t *testing.T) {
	for _, scheme := range []Scheme{SchemeHeader50k, SchemeHeader100k} {
		t.Run(scheme.String(), func(t *testing.T) {
			var first, second bytes.Buffer
			for _, output := range []*bytes.Buffer{&first, &second} {
				if _, err := NewSchemeEncryptWriter(output, powerToysSecurityKey, scheme); err != nil {
					t.Fatal(err)
				}
				if output.Len() != HeaderSize {
					t.Fatalf("header length = %d, want %d", output.Len(), HeaderSize)
				}
			}
			if bytes.Equal(first.Bytes()[:saltSize], second.Bytes()[:saltSize]) {
				t.Error("2 streams reused the same salt")
			}
			if bytes.Equal(first.Bytes()[saltSize:], second.Bytes()[saltSize:]) {
				t.Error("2 streams reused the same IV")
			}
		})
	}
}
