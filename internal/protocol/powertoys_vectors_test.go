func decodePowerToysHex(t *testing.T, value string) []byte {
	t.Helper()
	decoded, err := hex.DecodeString(value)
	if err != nil {
		t.Fatalf("invalid vector hex: %v", err)
	}
	return decoded
}

func TestDeriveKeyKnownAnswer(t *testing.T) {
	salt := decodePowerToysHex(t, powerToysSaltHex)
	for _, tc := range []struct {
		name string
		got  []byte
		want string
	}{
		{"legacy", DeriveKey(powerToysSecurityKey), powerToysLegacyKeyHex},
		{"header-50k", DeriveSchemeKey(powerToysSecurityKey, salt, SchemeHeader50k), powerToysHeader50kKeyHex},
		{"header-100k", DeriveSchemeKey(powerToysSecurityKey, salt, SchemeHeader100k), powerToysHeader100kKeyHex},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if want := decodePowerToysHex(t, tc.want); !bytes.Equal(tc.got, want) {
				t.Errorf("key = %x, want .NET key %x", tc.got, want)
			}
		})
	}
}

